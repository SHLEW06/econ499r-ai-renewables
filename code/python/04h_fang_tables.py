#!/usr/bin/env python3
"""Build Fang test tables (CSV and .tex) and the bridge chart from fang_results.csv. No new estimation.
Usage: python3 code/python/04h_fang_tables.py --date YYYY-MM-DD"""
import argparse, os, sys
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D

ap = argparse.ArgumentParser(); ap.add_argument("--date", required=True); a = ap.parse_args()
R = f"results/{a.date}/fang"; T = f"{R}/tables"; F = f"results/{a.date}/figures"
src = f"{R}/fang_results.csv"
if not os.path.exists(src): sys.exit(f"Missing input: {src}")
os.makedirs(T, exist_ok=True); os.makedirs(F, exist_ok=True)
r = pd.read_csv(src); r["smp"] = r["sample"]

def stars(p): return "" if pd.isna(p) else "***" if p < .01 else "**" if p < .05 else "*" if p < .1 else ""
def cell(e, s=None, p=None, d=4): return f"{e:.{d}f}{stars(p)}" + (f" ({s:.{d}f})" if s is not None and not pd.isna(s) else "")
def tex(df, path, note):
    cols = list(df.columns)
    t = ["% Generated by code/python/04h_fang_tables.py. Do not edit by hand.", "\\begin{tabular}{l" + "r" * (len(cols) - 1) + "}", "\\toprule", " & ".join(str(c).replace("_", "\\_").replace("%", "\\%") for c in cols) + " \\\\", "\\midrule"]
    for _, x in df.iterrows(): t.append(" & ".join(str(v).replace("_", "\\_").replace("%", "\\%").replace("&", "\\&") for v in x.values) + " \\\\")
    t += ["\\bottomrule", "\\end{tabular}", f"% {note}"]; open(path, "w").write("\n".join(t) + "\n")
def save(df, name, note): df.to_csv(f"{T}/{name}.csv", index=False); tex(df, f"{T}/{name}.tex", note)

# ---- Replication vs Fang Table 2 ----
PAPER = {"c1": (.0428, .015, "***"), "c2": (.0452, .015, "***"), "c3": (.0396, .015, "**"), "c4": (.0548, .016, "***"), "c5": (.0561, .019, "***"), "c6": (.0531, .019, "***")}
LAB = {"c1": "(1) AI", "c2": "(2) + EPU", "c3": "(3) + EP", "c4": "(4) + GDP", "c5": "(5) + POP", "c6": "(6) + EDU"}
def rep(spec_suffix, m, smp="51s2018_2021", vc="iid"):
    out = {}
    for c in PAPER:
        x = r[(r.block == "rep") & (r.spec == c + spec_suffix) & (r.ai_measure == m) & (r.smp == smp) & (r.vcov == vc) & (r.term == "AI")]
        assert len(x) == 1, (c, spec_suffix, m, smp, vc, len(x)); x = x.iloc[0]; out[c] = cell(x.estimate, x.se, x.pval)
    return out
rows = [("Fang Table 2 (published)", "AI postings, 2018-2021", 204, {c: f"{v[0]:.4f}{v[2]} ({v[1]:.3f})" for c, v in PAPER.items()}),
        ("Current SEDS", "AI postings, 2018-2021", 204, rep("", "aipostings")),
        ("Current SEDS, same vintage", "AI postings, 2019-2021", 153, rep("", "aipostings", "51s2019_2021")),
        ("Current SEDS, as first published", "AI postings, 2018-2021", 204, rep("-firstpub", "aipostings")),
        ("Approx. old SEDS, k = 2.3", "AI postings, 2018-2021", 204, rep("-ffe23", "aipostings")),
        ("Approx. old SEDS, k = 2.6", "AI postings, 2018-2021", 204, rep("-ffe26", "aipostings")),
        ("Approx. old SEDS, k = 2.9", "AI postings, 2018-2021", 204, rep("-ffe29", "aipostings")),
        ("Current SEDS", "Data-center jobs, 2018-2021", 204, rep("", "dcjobs")),
        ("Approx. old SEDS, k = 2.6", "Data-center jobs, 2018-2021", 204, rep("-ffe26", "dcjobs"))]
save(pd.DataFrame([{"Version": v, "Measure, sample": s, "N": n, **{LAB[c]: d[c] for c in PAPER}} for v, s, n, d in rows]), "replication", "State FE; conventional SEs; * p<0.1, ** p<0.05, *** p<0.01. Data-center jobs are the consistent series.")

# ---- Bridge ----
STEPS = [("s0-fang", "Fang's spec, 2018-2021"), ("s1-yearfe", "+ year FE"), ("s2-sample", "2019-2021 (years the lag can use)"), ("s3-lag", "+ lag AI one year"), ("s4-cluster", "+ cluster by state"), ("s5-extend", "+ extend the sample"), ("s6-noDC", "+ drop DC")]
b = []
for sp, lab in STEPS + [("s5b-extend1924", "Check: 2019-2024, with DC"), ("s6b-noDC1924", "Check: 2019-2024, no DC")]:
    row = {"Step": lab}
    for m, nm in (("aipostings", "ln(AI postings)"), ("aipostingshare", "ln(share of national postings)"), ("dcjobs", "ln(data-center jobs)"), ("dcper1000", "ln(jobs per 1,000)")):
        x = r[(r.block == "bridge") & (r.spec == sp) & (r.ai_measure == m)]
        row[nm] = "" if x.empty else f"{cell(x.iloc[0].estimate, x.iloc[0].se, x.iloc[0].pval)} [{int(x.iloc[0].N)}]"
    b.append(row)
save(pd.DataFrame(b), "bridge", "Current SEDS; N in brackets. Data-center jobs (BLS, one consistent series) are the more reliable extension measure. With year FE, the share row equals the postings row by construction.")

# ---- Moderation ----
mo = []
for sp, l1 in (("fang", "Fang spec"), ("twfe", "Two-way FE")):
    for ep, l2 in (("lnEPU", "Composite"), ("lnEPUN", "National"), ("lnEPUS", "State")):
        for m, nm in (("aipostings", "AI postings"), ("dcjobs", "Data-center jobs")):
            x = r[(r.block == "mod") & (r.spec == f"{sp}-{ep}") & (r.ai_measure == m)].set_index("term"); g = lambda t: cell(x.loc[t, "estimate"], x.loc[t, "se"], x.loc[t, "pval"])
            mo.append({"Spec": l1, "EPU": l2, "AI measure": nm, "AI x EPU": g("AI_x_EPU"), "AI slope, EPU p25": g("AI_slope_p25"), "AI slope, EPU p75": g("AI_slope_p75"), "N": int(x.loc["AI", "N"])})
save(pd.DataFrame(mo), "moderation", "Centered. Fang Table 6: composite 0.0114, national -0.0028, state 0.0160**.")

# ---- By type ----
P7 = {"lnWind": ("Wind", "0.1542***", 164), "lnSolar": ("Solar", "0.4970***", 204), "lnGeo": ("Geothermal", "0.0210", 204), "lnBio": ("Biomass", "-0.0535***", 204), "lnHydro": ("Hydro", "0.1160***", 192)}
ty = []
for y, (nm, pv, pn) in P7.items():
    row = {"Type": nm, "Fang Table 7": f"{pv} [{pn}]"}
    for sp, l1 in (("fang", "Fang spec"), ("twfe", "Two-way FE")):
        for m, l2 in (("aipostings", "postings"), ("dcjobs", "jobs")):
            x = r[(r.block == "type") & (r.spec == sp) & (r.ai_measure == m) & (r.outcome == y)].iloc[0]; row[f"{l1}, {l2}"] = f"{cell(x.estimate, x.se, x.pval)} [{int(x.N)}]"
    ty.append(row)
save(pd.DataFrame(ty), "by_type", "Zero-consumption state-years dropped. N in brackets.")

# ---- Heterogeneity ----
PF = {"elec": ("Electricity use", "-0.0025", "0.0730**"), "price": ("Electricity price", "0.0628**", "0.0334"), "rd": ("R&D", "0.0163", "0.0704**"), "income": ("Income", "0.1236***", "0.0005"), "net_producer": ("Net producer", "-0.0060", "0.0425*")}
he = []
for k in ("elec_mean", "elec_median", "price_mean", "price_median", "rd_mean", "rd_median", "income_mean", "income_median", "net_producer"):
    base = k.split("_m")[0]; lab = PF[base][0]; ty_ = "" if k == "net_producer" else (" (mean)" if k.endswith("mean") else " (median)")
    for m, nm in (("aipostings", "AI postings"), ("dcjobs", "Data-center jobs")):
        s = r[(r.block == "split") & (r.ai_measure == m)]; hi = s[s.spec == f"{k}-high"].iloc[0]; lo = s[s.spec == f"{k}-low"].iloc[0]
        i = r[(r.block == "inter") & (r.ai_measure == m) & (r.spec == f"twfe-{k}")].set_index("term"); d = i.loc["difference_high_minus_low"]
        he.append({"Split": lab + ty_, "AI measure": nm, "Fang high": PF[base][1], "Fang low": PF[base][2], "High group": f"{cell(hi.estimate, hi.se, hi.pval)} [{int(hi.N)}]", "Low group": f"{cell(lo.estimate, lo.se, lo.pval)} [{int(lo.N)}]", "Two-way FE: slope high": cell(i.loc["slope_high", "estimate"], i.loc["slope_high", "se"], i.loc["slope_high", "pval"]), "Two-way FE: slope low": cell(i.loc["slope_low", "estimate"], i.loc["slope_low", "se"], i.loc["slope_low", "pval"]), "Difference": cell(d.estimate, d.se, d.pval)})
save(pd.DataFrame(he), "heterogeneity", "Splits: Fang spec. Interactions in one model: lag, two-way FE, clustered, no DC. Exploratory: many tests, no multiplicity correction.")
reg = []
for rg, pf in (("West", "0.1176**"), ("South", "-0.0409"), ("Northeast", "0.0235"), ("Midwest", "0.0626**")):
    row = {"Region": rg, "Fang Table 5": pf}
    for m, nm in (("aipostings", "AI postings"), ("dcjobs", "Data-center jobs")):
        s = r[(r.block == "split") & (r.ai_measure == m) & (r.spec == f"region-{rg}")].iloc[0]; i = r[(r.block == "inter") & (r.ai_measure == m) & (r.spec == "twfe-region") & (r.term == f"slope_{rg}")].iloc[0]
        row[f"Split, {nm}"] = f"{cell(s.estimate, s.se, s.pval)} [{int(s.N)}]"; row[f"Two-way FE, {nm}"] = cell(i.estimate, i.se, i.pval)
    reg.append(row)
save(pd.DataFrame(reg), "regions", "Exploratory. Joint tests in fang_results.csv.")

# ---- Placebo and robustness ----
pl = []
for m, nm in (("aipostings", "AI postings"), ("dcjobs", "Data-center jobs")):
    x = r[(r.block == "placebo") & (r.ai_measure == m)]; g = lambda sp: x[x.spec == sp].iloc[0]
    pl.append({"AI measure": nm, "N": int(g("lag").N), "AI(t-1) alone": cell(g("lag").estimate, g("lag").se, g("lag").pval), "AI(t+1) alone": cell(g("lead").estimate, g("lead").se, g("lead").pval), "Both: lead": cell(g("both-lead").estimate, g("both-lead").se, g("both-lead").pval), "Both: lag": cell(g("both-lag").estimate, g("both-lag").se, g("both-lag").pval), "Within corr": f"{g('corr').estimate:.3f}"})
save(pd.DataFrame(pl), "placebo", "Final spec: two-way FE, clustered, no DC.")
ro = []
for sp, lab in (("base", "Final bridge spec"), ("share-outcome", "Outcome: ln(renewable share of total energy)"), ("drop2020", "Drop 2020"), ("rps", "Add LBNL current RPS/CES schedule"), ("ctrl4", "ctrl4 controls")):
    row = {"Check": lab}
    for m, nm in (("aipostings", "AI postings"), ("dcjobs", "Data-center jobs")):
        x = r[(r.block == "rob") & (r.spec == sp) & (r.ai_measure == m)].iloc[0]; row[nm] = f"{cell(x.estimate, x.se, x.pval)} [{int(x.N)}]"
    ro.append(row)
save(pd.DataFrame(ro), "robustness", "Two-way FE, lag, clustered, no DC.")

# ---- Bridge chart ----
BLUE, OR, INK, MUTE, GRID, SURF = "#2a78d6", "#eb6834", "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10, "axes.edgecolor": GRID, "text.color": INK, "axes.labelcolor": MUTE, "xtick.color": MUTE, "ytick.color": INK})
fig, ax = plt.subplots(1, 2, figsize=(12, 4.8), sharey=True, sharex=True, facecolor=SURF)
for A, m, title, c in ((ax[0], "aipostings", "ln(AI postings)", BLUE), (ax[1], "dcjobs", "ln(data-center jobs), the consistent series", OR)):
    A.set_facecolor(SURF); A.axvline(0, color=MUTE, lw=1)
    A.axhline(99, color=GRID)
    for i, (sp, lab) in enumerate(STEPS):
        x = r[(r.block == "bridge") & (r.spec == sp) & (r.ai_measure == m)].iloc[0]; y = len(STEPS) - 1 - i
        A.plot([x.ci_lo, x.ci_hi], [y, y], color=c, lw=2, solid_capstyle="round"); A.plot([x.estimate], [y], "o", ms=8, mec=c, mew=2, mfc=c if x.pval < .05 else SURF)
        A.text(.31, y, f"{x.estimate:+.3f}  N={int(x.N)}", va="center", ha="right", fontsize=8.5, color=MUTE)
    A.set_title(title, loc="left", fontsize=10.5, pad=8); A.grid(axis="x", color=GRID, lw=.8); A.set_axisbelow(True); A.set_xlim(-.36, .32)
    for s in ("top", "right", "left"): A.spines[s].set_visible(False)
    A.tick_params(axis="y", length=0); A.set_xlabel("AI coefficient, with 95% CI")
ax[0].set_yticks(range(len(STEPS))); ax[0].set_yticklabels([l for _, l in STEPS][::-1]); ax[0].set_ylim(-.7, len(STEPS) - .3)
fig.suptitle("From Fang's spec to ours, one change at a time", x=.012, y=.985, ha="left", fontsize=13, fontweight="bold")
fig.text(.012, .905, "On current SEDS, neither AI measure is significant once the lag, clustering and longer sample are in. Outcome: ln(renewable energy consumption).", fontsize=9.5, color=MUTE)
fig.legend(handles=[Line2D([], [], marker="o", color="none", mfc=MUTE, mec=MUTE, mew=2, ms=8, label="p < 0.05"), Line2D([], [], marker="o", color="none", mfc=SURF, mec=MUTE, mew=2, ms=8, label="p ≥ 0.05")], loc="lower right", ncol=2, frameon=False, fontsize=9)
fig.tight_layout(rect=(0, .05, 1, .89), w_pad=2)
fig.savefig(f"{F}/04h_bridge.png", dpi=180, facecolor=SURF)
open(f"{R}/PROVENANCE.md", "w").write(f"# Provenance: Fang test tables, {a.date}\n- Source rows: `{src}`, from `code/R/04h_fang_test.R --date {a.date}`\n- Built by: `code/python/04h_fang_tables.py --date {a.date}`\n- Fang's published numbers are typed from Tables 2-7 of the paper and labeled as such.\n")
print("tables:", sorted(os.listdir(T))[:20])
print(pd.DataFrame(b).to_string(index=False))
