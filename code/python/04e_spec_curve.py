#!/usr/bin/env python3
"""Build the 4e specification curve (CSV, .tex, PNG, PROVENANCE.md) from robustness.csv.
Usage: python3 code/python/04e_spec_curve.py --date YYYY-MM-DD"""
import argparse, os, subprocess, sys
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D

ap = argparse.ArgumentParser(); ap.add_argument("--date", required=True); a = ap.parse_args()
R = f"results/{a.date}/robustness"; F = f"results/{a.date}/figures"
src = f"{R}/robustness.csv"
if not os.path.exists(src): sys.exit(f"Missing input: {src}")
os.makedirs(F, exist_ok=True)
d = pd.read_csv(src, keep_default_na=True)
d["note"] = d["note"].fillna("")

AI = "ai_dc_per1000_lag1"
ROWS = [  # label, group, filter
 ("Baseline",                     "Baseline", lambda x: (x.spec=="base")),
 ("Drop 2020",                    "Sample",   lambda x: (x.spec=="drop2020")),
 ("Drop AK, HI",                  "Sample",   lambda x: (x.spec=="dropAKHI")),
 ("Drop VA",                      "Sample",   lambda x: (x.spec=="dropVA")),
 ("t-1 on placebo sample",        "Sample",   lambda x: (x.spec=="placebo-compare")),
 ("t-1 on 2017-2025",             "Sample",   lambda x: (x.spec=="distlag-compare")),
 ("Border SLX, own AI",           "Model",    lambda x: (x.spec=="slxborder")&(x.coef==AI)),
 ("Sum of t-1 to t-3, 2017-2025", "Model",    lambda x: (x.spec=="distlag")&(x.coef=="sum_lag1to3")),
 ("Long difference (fixed)",      "Model",    lambda x: (x.spec=="longdiff")&(x.vcov_type=="HC1")),
 ("Driscoll-Kraay SE",            "SE",       lambda x: (x.spec=="dk")),
 ("Conley 500 km SE",             "SE",       lambda x: (x.spec=="conley500")),
 ("Conley 1,000 km SE (unreliable)","SE",     lambda x: (x.spec=="conley1000")),
 ("Placebo: AI(t+1)",             "Placebo",  lambda x: (x.spec=="placebo")),
]
OUTS = [("ln_ec","ln_ec"),("ln_ee","ln_ee"),("renew_share","renew_share"),("new_renew_mw","new_renew_mw (MW)"),("new_renew_per_1000mw","new_renew_mw per\n1,000 MW of 2015 capacity")]
rows=[]
for lbl,grp,f in ROWS:
    s=d[f(d)]
    for o,_ in OUTS:
        r=s[s.outcome==o]
        if len(r)==0: continue
        assert len(r)==1,(lbl,o)
        r=r.iloc[0]
        rows.append(dict(spec_label=lbl,group=grp,outcome=o,estimate=r.estimate,se=r.se,pval=r.pval,ci_lo=r.ci_lo,ci_hi=r.ci_hi,N=int(r.N),vcov_type=r.vcov_type,tag=r.tag,status=r.status,note=r.note))
nr=d[d.status=="NOT_RUN"]
for _,r in nr.iterrows():
    rows.append(dict(spec_label="RPS control" if r.spec=="rps" else "Data-center MW",group="Not run",outcome=r.outcome,tag=r.tag,status=r.status,note=r.note))
sc=pd.DataFrame(rows); sc.to_csv(f"{R}/spec_curve.csv",index=False)

# ---- TeX ----
def cell(lbl,o):
    r=sc[(sc.spec_label==lbl)&(sc.outcome==o)]
    if len(r)==0: return "--"
    r=r.iloc[0]
    if r.status!="ok": return "not run"
    fmt="%.2f" if o.startswith("new_renew") else "%.4f"
    return (fmt%r.estimate)+" ("+("<0.001" if r.pval<.001 else "%.3f"%r.pval)+")"
labels=[x[0] for x in ROWS]+["RPS control","Data-center MW"]
t=["% Generated by code/python/04e_spec_curve.py. Do not edit by hand.","\\begin{tabular}{l"+"r"*len(OUTS)+"}","\\toprule","Specification & "+" & ".join(o.replace("_","\\_") for o,_ in OUTS)+" \\\\","\\midrule"]
for l in labels: t.append(l.replace("%","\\%")+" & "+" & ".join(cell(l,o).replace("<","$<$") for o,_ in OUTS)+" \\\\")
t+=["\\bottomrule","\\end{tabular}"]
open(f"{R}/spec_curve.tex","w").write("\n".join(t)+"\n")

# ---- Chart ----
BLUE,OR,INK,MUTE,GRID,SURF="#2a78d6","#eb6834","#0b0b0b","#52514e","#e4e3df","#fcfcfb"
GC={"Baseline":BLUE,"Placebo":OR}
plt.rcParams.update({"font.family":"DejaVu Sans","font.size":9,"axes.edgecolor":GRID,"text.color":INK,"axes.labelcolor":MUTE,"xtick.color":MUTE,"ytick.color":INK})
fig,ax=plt.subplots(1,len(OUTS),figsize=(14,5.6),sharey=True,facecolor=SURF)
y={l:len(ROWS)-1-i for i,(l,_,_) in enumerate(ROWS)}
for k,(o,title) in enumerate(OUTS):
    A=ax[k]; A.set_facecolor(SURF)
    A.axvline(0,color=MUTE,lw=1,zorder=1)
    for _,r in sc[(sc.outcome==o)&(sc.status=="ok")].iterrows():
        yy=y[r.spec_label]; c=GC.get(r.group,MUTE); dashed="unreliable" in r.spec_label
        if pd.notna(r.ci_lo): A.plot([r.ci_lo,r.ci_hi],[yy,yy],color=c,lw=2,solid_capstyle="round",ls=(0,(2,2)) if dashed else "-",zorder=2)
        A.plot([r.estimate],[yy],"o",ms=8,mec=c,mew=2,mfc=c if r.pval<.05 else SURF,zorder=3)
    A.set_title(title,fontsize=9.5,loc="left",color=INK,pad=8)
    A.grid(axis="x",color=GRID,lw=.8); A.set_axisbelow(True)
    for s in ["top","right","left"]: A.spines[s].set_visible(False)
    A.tick_params(axis="y",length=0); A.tick_params(axis="x",labelsize=8)
    A.locator_params(axis="x",nbins=4)
    for g in [y["Drop 2020"]+.5,y["Border SLX, own AI"]+.5,y["Driscoll-Kraay SE"]+.5,y["Placebo: AI(t+1)"]+.5]: A.axhline(g,color=GRID,lw=.8,zorder=0)
ax[0].set_yticks(list(y.values())); ax[0].set_yticklabels(list(y.keys()))
ax[0].set_ylim(-.7,len(ROWS)-.3)
fig.suptitle("The AI coefficient across specifications, with 95% CIs",x=.012,y=.985,ha="left",fontsize=13,fontweight="bold")
fig.text(.012,.915,"Next-year AI is significant for renew_share, while t-1 AI is not on the same sample. new_renew_mw is positive in raw MW but not when scaled.",fontsize=9.5,color=MUTE)
h=[Line2D([],[],marker="o",color=BLUE,mfc=BLUE,mec=BLUE,mew=2,ms=8,lw=2,label="Baseline"),
   Line2D([],[],marker="o",color=MUTE,mfc=MUTE,mec=MUTE,mew=2,ms=8,lw=2,label="Check"),
   Line2D([],[],marker="o",color=OR,mfc=OR,mec=OR,mew=2,ms=8,lw=2,label="Placebo"),
   Line2D([],[],marker="o",color="none",mfc=MUTE,mec=MUTE,mew=2,ms=8,label="p < 0.05"),
   Line2D([],[],marker="o",color="none",mfc=SURF,mec=MUTE,mew=2,ms=8,label="p ≥ 0.05")]
fig.legend(handles=h,loc="lower left",bbox_to_anchor=(.008,.0),ncol=5,frameon=False,fontsize=9)
fig.text(.99,.03,"State-clustered SEs unless the row names another. RPS control and data-center MW not run. Long difference: core outcomes only.",ha="right",fontsize=8,color=MUTE)
fig.tight_layout(rect=(0,.06,1,.895),w_pad=1.6)
fig.savefig(f"{F}/04e_spec_curve.png",dpi=180,facecolor=SURF); 

try: h_=subprocess.check_output(["git","rev-parse","--short","HEAD"],text=True).strip()
except Exception: h_="unknown"
open(f"{R}/PROVENANCE.md","w").write(f"""# Provenance: spec curve, {a.date}
- Source rows: `{src}`, from `code/R/04e_robustness.R --date {a.date}`
- Built by: `code/python/04e_spec_curve.py --date {a.date}`; base commit {h_}
- Outputs: `spec_curve.csv`, `spec_curve.tex`, `results/{a.date}/figures/04e_spec_curve.png`
- Every row in `spec_curve.csv` carries the tag of its source row. Nothing is typed by hand.
""")
print(sc[sc.status=="ok"].pivot(index="spec_label",columns="outcome",values="pval").reindex([x[0] for x in ROWS])[[o for o,_ in OUTS]].round(3).to_string())
